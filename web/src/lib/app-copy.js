/** Error copy: returns { t, d } for a code. */
export const errCopy = (code, lang, vars = {}) => {
  const e = A[`e_${code}`] || A.e_SIMULATION_FAILED;
  const [t, d] = e[lang === "id" ? 1 : 0];
  let dd = d;
  for (const n in vars) dd = dd.split(`{${n}}`).join(vars[n]);
  return { t, d: dd };
};
